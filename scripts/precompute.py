#!/usr/bin/env python3
"""Static data for the frontend (GitHub Pages has no backend).

    python scripts/precompute.py --sites-only          # sites_static.json/.js only (offline)
    python scripts/precompute.py                       # + 30-day bundle from today (UTC), Horizons
    python scripts/precompute.py --start 2026-11-15 --days 30 --mode horizons

Writes, under frontend/data/:
  sites_static.json   all sites from backend/data/sites.json + every horizon mask (360 values)
  bundle-YYYY-MM-DD-<days>d.json   same format as /api/bundle (series, DSN, masks, metadata)
  bundles.json        manifest of available bundles (newest first)
and frontend/js/sites_static.js (same content as sites_static.json, as a script, so the
app also works when index.html is opened from disk, where fetch() of local files is blocked).
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
from app import api, ephemeris, sites  # noqa: E402

OUT = ROOT / "frontend" / "data"
JS = ROOT / "frontend" / "js" / "sites_static.js"


def static_sites() -> dict:
    data = json.loads((ROOT / "backend" / "data" / "sites.json").read_text(encoding="utf-8"))
    out = []
    for s in data["sites"]:
        d = sites.public(s)
        d["horizon_mask"] = sites.load_mask(s["id"])
        out.append(d)
    return {"generator": "scripts/precompute.py", "lon_convention": data["lon_convention"], "sites": out}


def write_static_sites():
    OUT.mkdir(parents=True, exist_ok=True)
    payload = static_sites()
    txt = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    (OUT / "sites_static.json").write_text(txt, encoding="utf-8")
    JS.write_text("// Generated by scripts/precompute.py from backend/data/sites.json - do not edit.\n"
                  f"window.JP_SITES_STATIC = {txt};\n", encoding="utf-8")
    print(f"wrote {OUT / 'sites_static.json'} and {JS} ({len(payload['sites'])} sites)")


def build_bundle(start: datetime, days: int, mode: str) -> dict:
    p = {"start": start, "days": days, "mode": mode, "margin": 0.0, "height": 0.0, "dsn_min": 10.0, "return_hours": 8}
    out, srcs, errs, dsn, times = [], [], [], None, None
    for s in sites.select("all"):
        ser = ephemeris.site_series(s["lat"], s["lon"], start, days, mode)
        srcs.append(ser["source"])
        if ser["error"]:
            errs.append(ser["error"])
        dsn, times = dsn or ser["dsn"], times or ser["times"]
        out.append({**sites.public(s), "source": ser["source"], "horizon_mask": sites.load_mask(s["id"]),
                    "series": api._series_out(ser)})
    meta = api._meta(p, srcs, errs)
    meta["precomputed"] = True
    return api._jsonable({"meta": meta, "times": times, "dsn": dsn, "sites": out})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sites-only", action="store_true")
    ap.add_argument("--start", help="YYYY-MM-DD (UTC); default today")
    ap.add_argument("--days", type=int, default=30)
    ap.add_argument("--mode", default="horizons", choices=("horizons", "auto", "analytic"))
    ap.add_argument("--keep", type=int, default=3, help="bundles to keep in the manifest")
    a = ap.parse_args()
    write_static_sites()
    if a.sites_only:
        return 0
    now = datetime.now(timezone.utc)
    start = datetime.strptime(a.start, "%Y-%m-%d") if a.start else datetime(now.year, now.month, now.day)
    b = build_bundle(start, a.days, a.mode)
    name = f"bundle-{start:%Y-%m-%d}-{a.days}d.json"
    (OUT / name).write_text(json.dumps(b, separators=(",", ":")), encoding="utf-8")
    man_p = OUT / "bundles.json"
    man = json.loads(man_p.read_text()) if man_p.exists() else {"bundles": []}
    entry = {"file": name, "start": b["meta"]["start"], "days": a.days, "sources": b["meta"]["sources"],
             "generated_utc": b["meta"]["generated_utc"]}
    man["bundles"] = [entry] + [e for e in man["bundles"] if e["file"] != name]
    for old in man["bundles"][a.keep:]:
        (OUT / old["file"]).unlink(missing_ok=True)
    man["bundles"] = man["bundles"][:a.keep]
    man_p.write_text(json.dumps(man, indent=1))
    print(f"wrote {name}: sources={b['meta']['sources']}")
    if a.mode == "horizons" and b["meta"]["sources"] != ["horizons"]:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
